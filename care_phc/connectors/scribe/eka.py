"""Eka Scribe implementation of the scribe connector boundary.

All of it rides on the official `ekacare` SDK's v2rx client, which is the
EkaScribe half of the SDK:

  submit   client.v2rx.upload(file_paths, txn_id, action='ekascribe-v2', ...)
           which asks for a presigned S3 location, posts the audio to it, and
           then POSTs /voice/api/v2/transaction/init/{txn_id} to start the job
  fetch    GET voice/api/v3/status/{txn_id}, which is what
           V2RX.get_session_status(session_id, action='ekascribe-v2') calls.
           This file calls it through client.request(raw_response=True)
           instead, because the HTTP STATUS CODE IS THE ONLY SIGNAL of whether
           the job is finished and the SDK's helper throws it away: there is no
           status field in the body.

VERIFIED LIVE against https://api.eka.care on 2026-09-11: two uploads of the
same 92 second synthetic consultation generated by macOS `say`. What those two
runs actually observed, and nothing else:

  upload            2.2s, one POST /v1/file-upload, returns the S3 keys
  GET status  202   while the job ran, `data` empty
  GET status  200   at 25s on the first run and at 52s on the second, the same
                    audio both times. `data.output` carried eka_emr_template
                    and clinical_notes_template; `data.template_results` held
                    those again under `integration` and `custom`, plus the
                    transcript under `transcript` with template_id
                    "transcript". Every `value` is base64.
  data.audio_matrix {"quality": 1.0}, the only number in the whole response,
                    and it is about the recording, not about any field
  data.additional_data  the mode and model_type that were sent, echoed back

Two things this file handles that these runs did NOT produce, so they are
handled on Eka's documentation and not on observation: 206, and a 404 for a
transaction that does not exist. The 404 path is asserted in check.py against a
constructed body, which proves the handling and not the shape.

206 is the honest weakness of the polling. Eka documents it as partial success
and also returns it while templates are still running, and the body does not
say which, so a genuinely partial result would be indistinguishable from an
unfinished one and is waited on until the timeout. Failing to the form after a
bounded wait is the safe end of that ambiguity. Polling, not webhooks, and
`base.transcribe()` says why: no ingress here.

Compliance, enforced here rather than documented:
  - THE SDK PRINTS THE AUDIO FILENAME TO STDOUT. `V2RX.upload` and
    `EkaFileUploader._upload_single_file` both print, and one of those lines is
    "Successfully uploaded <basename>". stdout is a log. Every SDK call in this
    file runs inside contextlib.redirect_stdout, and check.py asserts that the
    captured text never reaches anything else.
  - The file is renamed to an opaque id before upload, because the S3 key is
    the basename: a recording called `ramesh-enc-002.wav` would put a patient's
    name in a third party's bucket.
  - The thread id is never sent. Eka does not need it, `additional_data` is
    carried in the object metadata, and an encounter id is an identifier.
  - Errors exit through one scrub, as the ABDM connector's do: Aadhaar shaped
    digits, file paths and audio filenames are removed before anything becomes
    an exception or a traceback.
  - A transcript is returned to the caller and put nowhere else. It is never
    part of an error message, so no error path can carry one.
"""
from __future__ import annotations

import base64
import contextlib
import io
import json
import os
import re
import uuid

from care_phc.connectors import redact
from care_phc.connectors.scribe import draft as to_draft
from care_phc.connectors.scribe.base import AudioRetention, ScribeError

STATUS = "voice/api/v3/status/"
ACTION = "ekascribe-v2"

# The three templates this bundle has a use for, and no others: the prose that
# fills the consult's text fields, the discrete JSON behind the diagnosis and
# the prescription, and the transcript the doctor reads the discrete values
# back against.
TEMPLATES = [
    {"template_id": "eka_emr_template", "codification_needed": True},
    {"template_id": "clinical_notes_template", "codification_needed": False},
    {"template_id": "transcript_template", "codification_needed": False},
]

# Still working. Anything else that is not ok is a failure.
PENDING = (202, 206)

# A path, or an audio file by name. The SDK's own errors are built out of both
# (`EkaUploadError(f"Upload failed for {file_name}: ...")`), and the name of a
# consultation recording is an identifier whatever the file is called.
_PATH = re.compile(r"(?:/[\w .()\-]+){2,}/?")
_AUDIO = re.compile(r"\b[\w .()\-]+\.(?:wav|mp3|m4a|aac|ogg|oga|flac|webm|aiff?)\b",
                    re.IGNORECASE)


def _scrub(text):
    """The one exit filter. Aadhaar first, from the shared pattern in
    care_phc/connectors/redact.py so the two connectors cannot drift apart on
    what an Aadhaar number looks like, then anything path or recording
    shaped."""
    out = redact.aadhaar(text)
    out = _AUDIO.sub("<audio-redacted>", out)
    return _PATH.sub("<path-redacted>", out)


def _fail(text, status=None, session=None):
    """Every failure leaves through here. Keeps the gateway's own code, which
    is the part a person can act on, and raises `from None` so nothing
    unscrubbed survives in __cause__ for a traceback to print."""
    code = None
    try:
        parsed = json.loads(text)
    except (ValueError, TypeError):
        parsed = None
    if isinstance(parsed, dict):
        err = parsed.get("error")
        code = err.get("code") if isinstance(err, dict) else parsed.get("code")
    raise ScribeError(_scrub(text)[:400], code=code, status=status,
                      session=session) from None


def _quiet(call):
    """Run an SDK call with its stdout swallowed and its errors translated.

    Both halves matter and both are about the same thing. The SDK prints the
    audio filename; the SDK's exceptions quote the audio path. Neither may get
    out, so this is the only place an SDK call is made from.
    """
    sink = io.StringIO()
    try:
        with contextlib.redirect_stdout(sink):
            return call()
    except ScribeError:
        raise
    except Exception as e:              # EkaScribeError, EkaUploadError, EkaCareError
        found = re.search(r"\b([1-5]\d\d)\b", str(e))
        _fail(str(e), status=int(found.group(1)) if found else None)


def _decode(value):
    """A template's base64 payload as text, or "" if it is not decodable.
    Content never raises: a mangled template is a missing field, and a missing
    field is a box the doctor fills in."""
    try:
        return base64.b64decode(value).decode("utf-8", "replace")
    except Exception:
        return ""


def templates(data):
    """{template_id: decoded text} from one status body.

    Both places are read. `data.output` carries the note and the EMR JSON;
    `data.template_results` carries those again plus the transcript, which
    never appears in `output` at all. First non empty value wins.
    """
    rows = list((data or {}).get("output") or [])
    for bucket in ((data or {}).get("template_results") or {}).values():
        rows.extend(bucket or [])
    out = {}
    for row in rows:
        name = row.get("template_id") or row.get("name") or ""
        text = _decode(row.get("value")) if row.get("value") else ""
        if name and text and not out.get(name):
            out[name] = text
    return out


class EkaScribe:
    """Implements ScribeConnector against Eka Scribe (v2rx)."""

    def __init__(self, base_url=None, client_id=None, client_secret=None, *,
                 client=None, retention=None, mode="consultation",
                 model="pro", language="en-IN"):
        # `client` is the seam, as in the ABDM connector: a real EkaCareClient
        # in production, a double in the checks, so no credential and no socket
        # are needed to test any of this.
        if client is None:
            from ekacare import EkaCareClient
            client = EkaCareClient(client_id=client_id, client_secret=client_secret,
                                   base_url=base_url or "https://api.eka.care")
        self._client = client
        self.retention = retention or AudioRetention()
        self._mode = mode
        self._model = model
        self._language = language

    # ---- plumbing ----------------------------------------------------------

    def _authed(self, call):
        """One retry after clearing the cached token. The SDK logs in once and
        keeps the string forever, so a 401 is the only sign it went stale. Same
        shape as EkaAbdm._authed, for the same SDK reason."""
        for attempt in (1, 2):
            try:
                return _quiet(call)
            except ScribeError as e:
                if e.status == 401 and attempt == 1:
                    self._client.set_access_token(None)
                    continue
                raise

    # ---- submit ------------------------------------------------------------

    def submit(self, audio_path, *, operation, thread=None):
        """Upload one recording and start the job. Returns the session id.

        Takes ownership of the file. It is renamed to the session id first: the
        S3 key is the basename, so whatever the browser or the clinic called
        the recording would otherwise be handed to a third party along with the
        audio. After that the name says nothing but "a recording", and the
        retention rule owns it.
        """
        session = "phc-" + uuid.uuid4().hex
        path = self._rename(audio_path, session)
        self.retention.hold(session, path, thread=thread)
        self._authed(lambda: self._client.v2rx.upload(
            [path], txn_id=session, action=ACTION,
            # `mode` and `model_type` are all Eka needs. additional_data rides
            # into the object metadata, so the thread, the patient and the
            # operation stay on this side of the wire.
            extra_data={"mode": self._mode, "model_type": self._model},
            output_format={"input_language": [self._language],
                           "output_template": TEMPLATES}))
        return session

    @staticmethod
    def _rename(audio_path, session):
        target = os.path.join(os.path.dirname(audio_path),
                              session + os.path.splitext(audio_path)[1])
        if os.path.abspath(target) == os.path.abspath(audio_path):
            return audio_path
        try:
            os.rename(audio_path, target)
        except OSError as e:
            _fail("The recording could not be prepared for upload: %s"
                  % e.__class__.__name__)
        return target

    # ---- fetch -------------------------------------------------------------

    def fetch(self, session, *, operation):
        """The Draft for that operation, or None while the job is still
        running. Never invents a value: a template that did not come back is a
        field the doctor fills in."""
        data = self._status(session)
        if data is None:
            return None
        found = templates(data)
        emr = found.get("eka_emr_template")
        try:
            emr = json.loads(emr) if emr else None
        except ValueError:
            emr = None
        return to_draft.build(
            operation,
            notes=found.get("clinical_notes_template"),
            emr=emr,
            transcript=found.get("transcript") or found.get("transcript_template"))

    def _status(self, session):
        """The status body, or None while it is still working. The code is the
        signal: 200 done, 202 or 206 not yet, anything else a failure."""
        def call():
            resp = self._client.request(method="GET", endpoint=STATUS + session,
                                        raw_response=True)
            if resp.status_code in PENDING:
                return None
            if not resp.ok:
                _fail(resp.text, status=resp.status_code, session=session)
            try:
                return (resp.json() or {}).get("data") or {}
            except ValueError:
                return {}

        return self._authed(call)

    def __repr__(self):
        return "<EkaScribe %s>" % self._client.base_url
